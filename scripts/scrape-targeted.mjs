// Temporary targeted scraper: pulls 5 pre-configured official-ATS companies
// into the live-jobs pool without running a full refresh.
//
//   node scripts/scrape-targeted.mjs
//
// Only the following companies are touched; every other company in
// src/data/live-jobs.js is preserved byte-for-byte in content.
import fs from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

import { searchMokaJobs } from './job-discovery/moka.mjs';
import { searchBeisenJobs } from './job-discovery/beisen.mjs';
import { searchHotjobJobs } from './job-discovery/hotjob.mjs';
import { isClosed } from './job-discovery/core.mjs';
import { shouldExcludeByPolicy, enrichCandidateFit } from './job-discovery/policy.mjs';
import { enrichProvenanceFields } from '../src/core/source-provenance.js';
import { curateDiscoveredJobs } from './job-discovery/granularity.mjs';
import { dedupeById } from './job-discovery/dedupe.mjs';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const config = JSON.parse(await fs.readFile(path.join(root, 'config/search-profile.json'), 'utf8'));
const officialSources = JSON.parse(await fs.readFile(path.join(root, 'config/official-sources.json'), 'utf8'));
const livePath = path.join(root, 'src/data/live-jobs.js');

const TARGETS = [
  { company: '欣锐科技', provider: 'moka' },
  { company: '新芯股份', provider: 'beisen' },
  { company: '蓝思科技', provider: 'beisen' },
  { company: '新能安', provider: 'hotjob' },
  { company: '中车戚墅堰所', provider: 'hotjob' }
];
const TARGET_NAMES = TARGETS.map((t) => t.company);

function normalizeSource(provider, source = {}) {
  const normalized = { ...source };
  if (!normalized.url && normalized.baseUrl) normalized.url = normalized.baseUrl;
  if (!normalized.graduationYear && config.graduationYear) normalized.graduationYear = config.graduationYear;
  return normalized;
}

function findSource(company, provider) {
  const list = officialSources?.[provider] || [];
  return list.find((s) => s.company === company) || null;
}

function cleanForStorage(job) {
  const {
    _searchText,
    _category,
    _subject,
    _sourceJobId,
    _recruitType,
    closed,
    excludeFromLiveBoard,
    ...clean
  } = job;
  return clean;
}

function asModule(jobs, meta) {
  const jobsJson = JSON.stringify(jobs, null, 2).replace(/\n]$/, '\n];').replace(/]$/, '];');
  const metaJson = JSON.stringify(meta, null, 2).replace(/\n}$/, '\n};').replace(/}$/, '};');
  return `// AUTO-GENERATED by scripts/refresh-jobs.mjs.\nexport const liveJobs = ${jobsJson}\n\nexport const discoveryMeta = ${metaJson}\n`;
}

// Mirrors dedupePreferOfficial in refresh-jobs.mjs exactly.
function dedupePreferOfficial(jobs = []) {
  const rank = (job) => job?.sourceType === 'official' ? 2 : job?.sourceType === 'secondary' ? 1 : 0;
  const map = new Map();

  for (const job of jobs) {
    if (!job?.id) continue;
    const key = `${String(job.company || '').trim().toLowerCase()}|${String(job.title || '').replace(/[\s【】〖〗()（）\-_]/g, '').toLowerCase()}|${String(job.city || '').trim().toLowerCase()}`;
    const previous = map.get(key);
    if (
      !previous
      || rank(job) > rank(previous)
      || (rank(job) === rank(previous) && String(job.publishedAt || '') > String(previous.publishedAt || ''))
    ) {
      map.set(key, job);
    }
  }

  return [...map.values()];
}

async function loadExisting() {
  try {
    const mod = await import(`${pathToFileURL(livePath).href}?t=${Date.now()}`);
    return { liveJobs: Array.isArray(mod.liveJobs) ? mod.liveJobs : [], meta: mod.discoveryMeta || {} };
  } catch {
    return { liveJobs: [], meta: {} };
  }
}

// --- Scrape each target company in isolation, capturing per-company status ---
const report = [];
const freshJobs = [];

let chromium = null;
try {
  chromium = (await import('playwright')).chromium;
} catch {}

for (const target of TARGETS) {
  const source = findSource(target.company, target.provider);
  const row = { company: target.company, provider: target.provider, raw: 0, kept: 0, status: 'ok', error: null };

  if (!source) {
    row.status = 'missing_source_config';
    row.error = `official-sources.json 中未找到 ${target.company} (${target.provider})`;
    report.push(row);
    console.warn(`[scrape-targeted] ${target.company}: ${row.error}`);
    continue;
  }

  const normalized = normalizeSource(target.provider, source);
  try {
    let result;
    if (target.provider === 'moka') {
      if (!chromium) throw new Error('Playwright Chromium unavailable (run: npx playwright install chromium)');
      result = await searchMokaJobs(config, [normalized], { chromium });
    } else if (target.provider === 'beisen') {
      result = await searchBeisenJobs(config, [normalized]);
    } else if (target.provider === 'hotjob') {
      result = await searchHotjobJobs(config, [normalized]);
    } else {
      throw new Error(`unsupported provider ${target.provider}`);
    }

    const jobs = Array.isArray(result?.jobs) ? result.jobs : [];
    row.raw = jobs.length;
    row.errors = Number(result?.stats?.errors || 0) + Number(result?.stats?.detailErrors || 0);
    row.stats = result?.stats || {};
    freshJobs.push(...jobs);
    console.log(`[scrape-targeted] ${target.company}: raw=${jobs.length} errors=${row.errors}`);
  } catch (error) {
    row.status = 'failed';
    row.error = String(error?.message || error);
    console.warn(`[scrape-targeted] ${target.company} FAILED: ${row.error}`);
  }
  report.push(row);
}

// --- Same pipeline as refresh-jobs.mjs ---
const curated = curateDiscoveredJobs(freshJobs);
const granularityDropped = curated.filter((j) => j.excludeFromLiveBoard).length;
const pipelineKept = curated
  .filter((j) => !j.excludeFromLiveBoard)
  .filter((j) => !shouldExcludeByPolicy(j))
  .map((j) => enrichCandidateFit(j, config))
  .map((j) => enrichProvenanceFields(j))
  .filter((j) => !isClosed('', j.deadline));

// Update per-company kept counts after pipeline.
for (const row of report) {
  row.kept = pipelineKept.filter((j) => j.company === row.company).length;
}

// --- Merge into existing pool: drop the 5 target companies' old rows ---
const { liveJobs: existing, meta: existingMeta } = await loadExisting();
const untouched = existing.filter((j) => !TARGET_NAMES.includes(j.company));
console.log(`[scrape-targeted] existing=${existing.length} untouched=${untouched.length} fresh=${pipelineKept.length}`);

const combined = [...untouched, ...pipelineKept];
const deduped = dedupeById(dedupePreferOfficial(combined));
const finalJobs = deduped
  .sort(
    (a, b) =>
      String(b.publishedAt || '').localeCompare(String(a.publishedAt || ''))
      || String(b.company || '').localeCompare(String(a.company || ''))
  );

const meta = {
  ...existingMeta,
  updatedAt: new Date().toISOString(),
  totalJobs: finalJobs.length,
  totalCompanies: new Set(finalJobs.map((j) => j.company)).size,
  targetedRefresh: {
    runAt: new Date().toISOString(),
    granularityDropped,
    companies: report.map((r) => ({
      company: r.company,
      provider: r.provider,
      status: r.status,
      raw: r.raw,
      kept: r.kept,
      errors: r.errors || 0,
      error: r.error
    }))
  }
};

await fs.writeFile(livePath, asModule(finalJobs.map(cleanForStorage), meta), 'utf8');

console.log('\n[scrape-targeted] SUMMARY');
for (const row of report) {
  console.log(`  - ${row.company} (${row.provider}): status=${row.status} raw=${row.raw} kept=${row.kept}${row.error ? ' error=' + row.error : ''}`);
}
console.log(`[scrape-targeted] DONE jobs=${finalJobs.length} companies=${meta.totalCompanies} -> ${path.relative(root, livePath)}`);
