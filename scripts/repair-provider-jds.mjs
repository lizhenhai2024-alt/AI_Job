#!/usr/bin/env node
/**
 * Targeted official-provider JD repair.
 *
 * Purpose: repair provider rows whose historical normalized JD fields were
 * contaminated without waiting for the full multi-source refresh pipeline.
 * Only providers listed below are replaced, and only when their fresh official
 * snapshot is complete, error-free and non-empty. All other jobs are preserved.
 */
import fs from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { searchMeituanJobs } from './job-discovery/meituan.mjs';
import { searchXiaohongshuJobs } from './job-discovery/xiaohongshu.mjs';
import { resolveJdEvidence } from './job-discovery/policy.mjs';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const profilePath = path.join(root, 'config/search-profile.json');
const sourcesPath = path.join(root, 'config/official-sources.json');
const livePath = path.join(root, 'src/data/live-jobs.js');

export const REPAIR_PROVIDERS = [
  { key: 'meituan', idPrefix: 'meituan-', searcher: searchMeituanJobs },
  { key: 'xiaohongshu', idPrefix: 'xiaohongshu-', searcher: searchXiaohongshuJobs }
];

function asSources(value) {
  if (Array.isArray(value)) return value.filter(Boolean);
  return value ? [value] : [];
}

export function validateFreshSnapshot(provider, result) {
  const stats = result?.stats || {};
  const jobs = Array.isArray(result?.jobs) ? result.jobs : [];
  const errors = Number(stats.errors || 0) + Number(stats.detailErrors || 0);
  if (stats.snapshotComplete !== true) {
    throw new Error(`${provider}: fresh snapshot is incomplete`);
  }
  if (errors > 0) {
    throw new Error(`${provider}: fresh snapshot has ${errors} errors`);
  }
  if (jobs.length === 0) {
    throw new Error(`${provider}: fresh snapshot returned zero jobs`);
  }
  return jobs;
}

export function replaceProviderJobs(existingJobs, freshJobs, idPrefix) {
  const existing = Array.isArray(existingJobs) ? existingJobs : [];
  const fresh = Array.isArray(freshJobs) ? freshJobs : [];
  const untouched = existing.filter((job) => !String(job?.id || '').startsWith(idPrefix));
  return [...untouched, ...fresh];
}

function cleanForStorage(job = {}) {
  const {
    _searchText,
    _category,
    _subject,
    _sourceJobId,
    _recruitType,
    _recruitGroup,
    _recruitStatus,
    closed,
    excludeFromLiveBoard,
    candidateFit,
    jdEvidence,
    ...clean
  } = job;
  if (Array.isArray(clean.riskTags)) {
    clean.riskTags = clean.riskTags.filter((tag) => !String(tag).startsWith('适配风险：'));
  }
  return { ...clean, jdEvidence: resolveJdEvidence(job) };
}

function asModule(jobs, meta) {
  const jobsJson = JSON.stringify(jobs, null, 2).replace(/\n]$/, '\n];').replace(/]$/, '];');
  const metaJson = JSON.stringify(meta, null, 2).replace(/\n}$/, '\n};').replace(/}$/, '};');
  return `// AUTO-GENERATED by targeted provider JD repair.\nexport const liveJobs = ${jobsJson}\n\nexport const discoveryMeta = ${metaJson}\n`;
}

async function loadLiveModule() {
  return import(`${pathToFileURL(livePath).href}?t=${Date.now()}`);
}

export async function repairProviderSnapshots({
  profile,
  officialSources,
  existingJobs,
  providers = REPAIR_PROVIDERS,
  now = new Date()
}) {
  let jobs = [...(existingJobs || [])];
  const repaired = {};

  for (const provider of providers) {
    const sources = asSources(officialSources?.[provider.key]);
    if (!sources.length) throw new Error(`${provider.key}: no official source configured`);

    const fresh = [];
    for (const rawSource of sources) {
      const source = {
        ...rawSource,
        url: rawSource.url || rawSource.baseUrl || '',
        graduationYear: rawSource.graduationYear || profile?.graduationYear || '2027'
      };
      const result = await provider.searcher(profile, source, {
        maxJobs: source.maxJobs,
        pageSize: source.pageSize,
        maxPages: source.maxPages,
        now
      });
      fresh.push(...validateFreshSnapshot(provider.key, result));
    }

    const before = jobs.filter((job) => String(job?.id || '').startsWith(provider.idPrefix)).length;
    const cleanedFresh = fresh.map(cleanForStorage);
    jobs = replaceProviderJobs(jobs, cleanedFresh, provider.idPrefix);
    repaired[provider.key] = { before, after: cleanedFresh.length };
  }

  jobs.sort((a, b) =>
    String(b.publishedAt || '').localeCompare(String(a.publishedAt || ''))
    || String(b.company || '').localeCompare(String(a.company || ''))
  );
  return { jobs, repaired };
}

async function main() {
  const [profileText, sourcesText, liveModule] = await Promise.all([
    fs.readFile(profilePath, 'utf8'),
    fs.readFile(sourcesPath, 'utf8'),
    loadLiveModule()
  ]);
  const profile = JSON.parse(profileText);
  const officialSources = JSON.parse(sourcesText);
  const existingJobs = Array.isArray(liveModule.liveJobs) ? liveModule.liveJobs : [];
  const previousMeta = liveModule.discoveryMeta || {};
  const now = new Date();

  const { jobs, repaired } = await repairProviderSnapshots({
    profile, officialSources, existingJobs, now
  });

  const meta = {
    ...previousMeta,
    updatedAt: now.toISOString(),
    totalJobs: jobs.length,
    totalCompanies: new Set(jobs.map((job) => job.company).filter(Boolean)).size,
    targetedRepair: {
      repairedAt: now.toISOString(),
      providers: repaired
    }
  };

  await fs.writeFile(livePath, asModule(jobs, meta), 'utf8');
  for (const [provider, counts] of Object.entries(repaired)) {
    console.log(`[provider-jd-repair:${provider}] replaced=${counts.before} fresh=${counts.after}`);
  }
  console.log(`[provider-jd-repair] DONE jobs=${jobs.length} companies=${meta.totalCompanies}`);
}

const isDirect = process.argv[1]
  && path.resolve(process.argv[1]) === path.resolve(fileURLToPath(import.meta.url));
if (isDirect) {
  main().catch((error) => {
    console.error(`[provider-jd-repair] FAIL: ${error?.stack || error}`);
    process.exitCode = 1;
  });
}
