#!/usr/bin/env node
import fs from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { searchUniversityJobs } from './university.mjs';
import { dedupePreferOfficial } from './dedupe.mjs';
import { relevanceScore, isClosed } from './core.mjs';
import { shouldExcludeByPolicy, enrichCandidateFit } from './policy.mjs';
import { enrichProvenanceFields } from '../../src/core/source-provenance.js';
import { curateDiscoveredJobs } from './granularity.mjs';
import { evaluateSourceHealth } from './source-health.mjs';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../..');
const profile = JSON.parse(await fs.readFile(path.join(root, 'config/search-profile.json'), 'utf8'));
const universityConfig = JSON.parse(await fs.readFile(path.join(root, 'config/university-sources.json'), 'utf8'));
const livePath = path.join(root, 'src/data/live-jobs.js');
const sourceHealthPath = path.join(root, 'src/data/source-health.js');

async function loadModule(filePath) {
  return import(`${pathToFileURL(filePath).href}?t=${Date.now()}`);
}

function cleanForStorage(job) {
  const { _searchText, _category, _subject, _sourceJobId, _recruitType, closed, excludeFromLiveBoard, ...clean } = job;
  return clean;
}

function asModule(jobs, meta) {
  return `// AUTO-GENERATED by scripts/refresh-jobs.mjs + university enrichment.\nexport const liveJobs = ${JSON.stringify(jobs, null, 2)};\n\nexport const discoveryMeta = ${JSON.stringify(meta, null, 2)};\n`;
}

function healthModule(health, updatedAt) {
  return `// AUTO-GENERATED by job discovery refresh.\nexport const sourceHealth = ${JSON.stringify({ ...health, updatedAt }, null, 2)};\n`;
}

function combineHealth(existing = {}, universityStats = {}, sources = []) {
  const baseCompanies = (existing.companies || []).filter((item) => item.provider !== 'university');
  const universityCompanies = sources.map((source) => {
    const stats = universityStats.perPortal?.[source.school] || {};
    return evaluateSourceHealth('university', { ...source, company: source.school }, stats);
  });
  const companies = [...baseCompanies, ...universityCompanies];
  const counts = companies.reduce((acc, item) => {
    acc[item.status] = (acc[item.status] || 0) + 1;
    return acc;
  }, {});
  return {
    companies,
    counts,
    total: companies.length,
    healthy: companies.filter((item) => item.healthy).length,
    attention: companies.filter((item) => !item.healthy).length
  };
}

const liveModule = await loadModule(livePath);
const healthModuleCurrent = await loadModule(sourceHealthPath).catch(() => ({ sourceHealth: {} }));
const existingJobs = Array.isArray(liveModule.liveJobs) ? liveModule.liveJobs : [];
const existingMeta = liveModule.discoveryMeta || {};
const existingHealth = healthModuleCurrent.sourceHealth || {};

const university = await searchUniversityJobs(profile, universityConfig);
const curated = curateDiscoveredJobs(university.jobs || []);
const freshUniversityJobs = curated
  .filter((job) => !job.excludeFromLiveBoard)
  .filter((job) => !shouldExcludeByPolicy(job))
  .map(enrichCandidateFit);

const now = new Date();
const merged = dedupePreferOfficial([...existingJobs, ...freshUniversityJobs])
  .filter((job) => !isClosed('', job.deadline, now) && !shouldExcludeByPolicy(job))
  .sort((a, b) => {
    const scoreDiff = relevanceScore(b, profile) - relevanceScore(a, profile);
    if (scoreDiff) return scoreDiff;
    if (a.sourceType !== b.sourceType) return a.sourceType === 'official' ? -1 : b.sourceType === 'official' ? 1 : 0;
    return String(b.publishedAt || b.discoveredAt || '').localeCompare(String(a.publishedAt || a.discoveredAt || ''));
  })
  .slice(0, Number(profile.maxJobs || 300))
  .map(cleanForStorage);

const activeSources = (universityConfig.schools || []).filter((source) => source.enabled && source.listUrls?.length);
const finalJobs = merged.map(enrichProvenanceFields);
const updatedAt = new Date().toISOString();
const sourceHealth = combineHealth(existingHealth, university.stats || {}, activeSources);
const companies = new Set(merged.map((job) => job.company).filter(Boolean));
const meta = {
  ...existingMeta,
  updatedAt,
  source: '多源：公司官方招聘官网/API + 高校就业信息网 + 牛客公开职位 + 官网核验具体岗位',
  mode: '岗位发现/情报库：公司官方源优先 + 重点高校就业网补充 + 多源证据合并去重；最终 S/A/B 与匹配度由 campus-job-board 负责',
  stats: {
    ...(existingMeta.stats || {}),
    sources: { ...(existingMeta.stats?.sources || {}), university: university.stats },
    sourceHealth,
    university: {
      targetSchools: (universityConfig.schools || []).length,
      activeSchools: activeSources.length,
      discovered: university.stats?.listed || 0,
      keptBeforeGranularity: university.stats?.keptJobs || 0,
      keptAfterGranularityAndPolicy: freshUniversityJobs.length
    },
    totalJobs: merged.length,
    companies: companies.size
  },
  note: `${existingMeta.note || ''} 高校渠道覆盖策略：985/211/双一流及外语外贸特色高校；高校就业网作为发现与交叉取证来源，正式投递前仍回公司官方校招官网复核。`.trim()
};

await fs.writeFile(livePath, asModule(finalJobs, meta), 'utf8');
await fs.writeFile(sourceHealthPath, healthModule(sourceHealth, updatedAt), 'utf8');
console.log(`[university-refresh] activeSchools=${activeSources.length} listed=${university.stats?.listed || 0} rawKept=${university.stats?.keptJobs || 0} finalAdded=${freshUniversityJobs.length}`);
console.log(`[university-refresh] mergedPool=${finalJobs.length} companies=${companies.size} crossEvidence=${finalJobs.filter((job) => (job.sourceEvidence || []).length > 1).length}`);
