#!/usr/bin/env node
import fs from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const sourcePath = path.join(root, 'config/official-sources.json');
const outputPath = path.join(root, 'src/data/source-registry.js');
const config = JSON.parse(await fs.readFile(sourcePath, 'utf8'));

export function flattenOfficialSources(sources = config) {
  const rows = [];
  for (const [provider, value] of Object.entries(sources)) {
    const entries = Array.isArray(value) ? value : value ? [value] : [];
    for (const entry of entries) {
      if (entry?.company) rows.push({ provider, company: entry.company });
    }
  }
  return rows;
}

const rows = flattenOfficialSources();
const output = `// AUTO-GENERATED by scripts/build-source-registry.mjs.\nexport const sourceRegistry = ${JSON.stringify(rows, null, 2)};\n`;
await fs.writeFile(outputPath, output, 'utf8');
console.log(`Built source registry: ${rows.length} official company/source links.`);
