#!/usr/bin/env node
import fs from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { enrichJobCompensation } from '../src/core/compensation.js';
import { enrichJobHeadcount } from '../src/core/headcount.js';
import { normalizeJobLanguages } from './job-discovery/languages.mjs';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const livePath = path.join(root, 'src/data/live-jobs.js');
const mod = await import(`${pathToFileURL(livePath).href}?t=${Date.now()}`);
const jobs = Array.isArray(mod.liveJobs) ? mod.liveJobs : [];
const discoveryMeta = mod.discoveryMeta || {};

// Final field normalization runs after all discovery sources (including university
// evidence) have been merged, so every stored live job receives the same language
// semantics regardless of which adapter produced it.
const languageNormalized = jobs.map(normalizeJobLanguages);
const enriched = languageNormalized.map(enrichJobCompensation).map(enrichJobHeadcount);
const disclosed = enriched.filter((job) => job.compensation?.disclosed).length;
const officialDisclosed = enriched.filter((job) => job.sourceType === 'official' && job.compensation?.disclosed).length;
const annualized = enriched.filter((job) => job.compensation?.annualMin != null).length;
const headcountDisclosed = enriched.filter((job) => job.headcount?.disclosed).length;
const headcountOfficial = enriched.filter((job) => job.sourceType === 'official' && job.headcount?.disclosed).length;
const headcountJobLevel = enriched.filter((job) => job.headcount?.disclosed && job.headcount?.scope === 'job').length;
const headcountProgramLevel = enriched.filter((job) => job.headcount?.disclosed && job.headcount?.scope === 'program').length;
const publicationKnown = enriched.filter((job) => /^\d{4}-\d{2}-\d{2}$/.test(String(job.publishedAt || ''))).length;
const withLanguages = enriched.filter((job) => (job.languages || []).length > 0).length;
const mandatoryLanguageJobs = enriched.filter((job) => (job.mandatoryLanguages || []).length > 0).length;
const preferredLanguageJobs = enriched.filter((job) => (job.preferredLanguages || []).length > 0).length;
const updatedAt = new Date().toISOString();
const meta = {
  ...discoveryMeta,
  updatedAt,
  stats: {
    ...(discoveryMeta.stats || {}),
    languages: {
      withLanguages,
      emptyLanguages: Math.max(0, enriched.length - withLanguages),
      mandatoryLanguageJobs,
      preferredLanguageJobs,
      totalJobs: enriched.length
    },
    compensation: {
      disclosed,
      officialDisclosed,
      annualized,
      undisclosed: Math.max(0, enriched.length - disclosed),
      totalJobs: enriched.length
    },
    headcount: {
      disclosed: headcountDisclosed,
      officialDisclosed: headcountOfficial,
      jobLevel: headcountJobLevel,
      programLevel: headcountProgramLevel,
      undisclosed: Math.max(0, enriched.length - headcountDisclosed),
      totalJobs: enriched.length
    },
    publication: {
      known: publicationKnown,
      unknown: Math.max(0, enriched.length - publicationKnown),
      totalJobs: enriched.length
    }
  },
  note: `${discoveryMeta.note || ''} 语言字段规则：优先按标题/JD正文重新识别并标准化 languages，同时区分 mandatoryLanguages / preferredLanguages；仅在正文无语言证据时保留适配器已有字段。薪资情报规则：仅解析来源页/JD明确披露的薪资；月薪转年薪按明确薪数计算，未写薪数时仅按12薪估算并显式标记；“面议/未披露”不猜测。HC规则：只保留ATS结构化字段或JD明确招聘人数，区分岗位HC(job)与整届/项目招聘规模(program)，公司员工规模不得推断为HC。发布日期只认来源披露的publishedAt/datePosted/PostDate等字段，discoveredAt不得冒充发布日期。`.trim()
};

const jobsJson = JSON.stringify(enriched, null, 2).replace(/\n]$/, '\n];').replace(/]$/, '];');
const metaJson = JSON.stringify(meta, null, 2).replace(/\n}$/, '\n};').replace(/}$/, '};');
const output = `// AUTO-GENERATED by job discovery refresh + language/compensation enrichment.\nexport const liveJobs = ${jobsJson}\n\nexport const discoveryMeta = ${metaJson}\n`;
await fs.writeFile(livePath, output, 'utf8');
console.log(`[languages] detected=${withLanguages}/${enriched.length} mandatory=${mandatoryLanguageJobs} preferred=${preferredLanguageJobs}`);
console.log(`[compensation] disclosed=${disclosed}/${enriched.length} official=${officialDisclosed} annualized=${annualized}`);
console.log(`[headcount] disclosed=${headcountDisclosed}/${enriched.length} official=${headcountOfficial} job=${headcountJobLevel} program=${headcountProgramLevel}`);
console.log(`[publication] known=${publicationKnown}/${enriched.length}`);
