#!/usr/bin/env node
import fs from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { enrichJobCompensation } from '../src/core/compensation.js';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const livePath = path.join(root, 'src/data/live-jobs.js');
const mod = await import(`${pathToFileURL(livePath).href}?t=${Date.now()}`);
const jobs = Array.isArray(mod.liveJobs) ? mod.liveJobs : [];
const discoveryMeta = mod.discoveryMeta || {};

const enriched = jobs.map(enrichJobCompensation);
const disclosed = enriched.filter((job) => job.compensation?.disclosed).length;
const officialDisclosed = enriched.filter((job) => job.sourceType === 'official' && job.compensation?.disclosed).length;
const annualized = enriched.filter((job) => job.compensation?.annualMin != null).length;
const updatedAt = new Date().toISOString();
const meta = {
  ...discoveryMeta,
  updatedAt,
  stats: {
    ...(discoveryMeta.stats || {}),
    compensation: {
      disclosed,
      officialDisclosed,
      annualized,
      undisclosed: Math.max(0, enriched.length - disclosed),
      totalJobs: enriched.length
    }
  },
  note: `${discoveryMeta.note || ''} 薪资情报规则：仅解析来源页/JD明确披露的薪资；月薪转年薪按明确薪数计算，未写薪数时仅按12薪估算并显式标记；“面议/未披露”不猜测。`.trim()
};

const output = `// AUTO-GENERATED by job discovery refresh + compensation enrichment.\nexport const liveJobs = ${JSON.stringify(enriched, null, 2)};\n\nexport const discoveryMeta = ${JSON.stringify(meta, null, 2)};\n`;
await fs.writeFile(livePath, output, 'utf8');
console.log(`[compensation] disclosed=${disclosed}/${enriched.length} official=${officialDisclosed} annualized=${annualized}`);
