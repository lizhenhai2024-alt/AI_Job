#!/usr/bin/env node
import fs from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const sourcePath = path.join(root, 'config/company-requests.json');
const outputPath = path.join(root, 'src/data/company-requests.js');
const requests = JSON.parse(await fs.readFile(sourcePath, 'utf8'));
if (!Array.isArray(requests)) throw new Error('config/company-requests.json must be an array');
const output = `// AUTO-GENERATED by scripts/build-company-requests.mjs.\nexport const companyRequests = ${JSON.stringify(requests, null, 2)};\n`;
await fs.writeFile(outputPath, output, 'utf8');
console.log(`Built company request module: ${requests.length} requests.`);
