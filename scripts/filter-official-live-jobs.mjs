#!/usr/bin/env node
import fs from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const livePath = path.join(root, 'src/data/live-jobs.js');

export function keepOfficialJobs(jobs = []) {
  return (jobs || []).filter((job) => job?.sourceType === 'official');
}

function asModule(jobs, meta) {
  const jobsJson = JSON.stringify(jobs, null, 2).replace(/\n]$/, '\n];').replace(/]$/, '];');
  const metaJson = JSON.stringify(meta, null, 2).replace(/\n}$/, '\n};').replace(/}$/, '};');
  return `// AUTO-GENERATED by job discovery refresh; production pool is official-source only.\nexport const liveJobs = ${jobsJson}\n\nexport const discoveryMeta = ${metaJson}\n`;
}

async function main() {
  const mod = await import(`${pathToFileURL(livePath).href}?t=${Date.now()}`);
  const original = Array.isArray(mod.liveJobs) ? mod.liveJobs : [];
  const official = keepOfficialJobs(original);
  const excluded = original.length - official.length;
  const companies = new Set(official.map((job) => job.company).filter(Boolean));
  const existingMeta = mod.discoveryMeta || {};
  const meta = {
    ...existingMeta,
    updatedAt: new Date().toISOString(),
    source: '公司官方招聘官网/API；高校就业网、牛客等仅用于发现与交叉取证，不进入生产岗位池',
    mode: '岗位发现/情报库：生产 liveJobs 仅保留 official；最终 S/A/B 与匹配度由 campus-job-board 负责',
    stats: {
      ...(existingMeta.stats || {}),
      totalJobs: official.length,
      companies: companies.size,
      sourcePolicy: {
        production: 'official-only',
        excludedNonOfficial: excluded
      }
    },
    note: `${existingMeta.note || ''} 生产岗位池强制 official-only；高校就业网、牛客等保留为发现/交叉取证渠道，不直接进入 liveJobs。`.trim()
  };

  await fs.writeFile(livePath, asModule(official, meta), 'utf8');
  console.log(`[official-only] before=${original.length} after=${official.length} excluded=${excluded} companies=${companies.size}`);
}

const invokedAsScript = process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url);
if (invokedAsScript) {
  await main();
}
