import fs from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { searchNowcoderJobs } from './job-discovery/nowcoder.mjs';
import { dedupeJobs, relevanceScore, isClosed } from './job-discovery/core.mjs';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const config = JSON.parse(await fs.readFile(path.join(root, 'config/search-profile.json'), 'utf8'));
const livePath = path.join(root, 'src/data/live-jobs.js');

async function loadExisting() {
  try {
    const mod = await import(`${pathToFileURL(livePath).href}?t=${Date.now()}`);
    return Array.isArray(mod.liveJobs) ? mod.liveJobs : [];
  } catch { return []; }
}

function cleanForStorage(job) {
  const { _searchText, closed, ...clean } = job;
  return clean;
}

function asModule(jobs, meta) {
  return `// AUTO-GENERATED by scripts/refresh-jobs.mjs.\nexport const liveJobs = ${JSON.stringify(jobs, null, 2)};\n\nexport const discoveryMeta = ${JSON.stringify(meta, null, 2)};\n`;
}

const existing = await loadExisting();
let result;
try {
  result = await searchNowcoderJobs(config);
} catch (error) {
  console.warn(`[job-refresh] source unavailable: ${error.message}`);
  console.warn('[job-refresh] keeping existing live job pool unchanged.');
  process.exit(0);
}

console.log(`[job-refresh] discovered=${result.stats.discoveredUrls} scanned=${result.stats.scannedPages} kept=${result.stats.keptJobs} errors=${result.stats.errors}`);
if (!result.jobs.length) {
  console.warn('[job-refresh] no fresh matching jobs found; keeping existing live job pool unchanged.');
  process.exit(0);
}

// Keep only manually curated seed entries from the previous pool. Auto-generated entries are rebuilt
// from source on every successful refresh so parser/filter improvements can remove stale false positives.
const retainedSeeds = existing.filter((job) => !job.discoveredAt);
const now = new Date();
const merged = dedupeJobs([...result.jobs, ...retainedSeeds])
  .filter((job) => !isClosed('', job.deadline, now))
  .sort((a,b) => relevanceScore(b, config) - relevanceScore(a, config) || String(b.publishedAt || '').localeCompare(String(a.publishedAt || '')))
  .slice(0, Number(config.maxJobs || 120))
  .map(cleanForStorage);

const companies = new Set(merged.map((job) => job.company).filter(Boolean));
const meta = {
  updatedAt: new Date().toISOString(),
  source: '牛客公开职位',
  mode: '自动公司发现 + 公开职位索引 + 前端画像精排',
  stats: { ...result.stats, retainedSeeds: retainedSeeds.length, totalJobs: merged.length, companies: companies.size },
  note: '公开二手来源用于发现；投递前请打开来源，并优先回到公司校招官网核验。'
};

await fs.writeFile(livePath, asModule(merged, meta), 'utf8');
console.log(`[job-refresh] wrote ${merged.length} jobs across ${companies.size} companies; retainedSeeds=${retainedSeeds.length}.`);
