import fs from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { searchNowcoderJobs } from './job-discovery/nowcoder.mjs';
import { searchMokaJobs } from './job-discovery/moka.mjs';
import { searchBeisenJobs } from './job-discovery/beisen.mjs';
import { searchAnkerJobs } from './job-discovery/anker.mjs';
import { relevanceScore, isClosed } from './job-discovery/core.mjs';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const config = JSON.parse(await fs.readFile(path.join(root, 'config/search-profile.json'), 'utf8'));
const officialSources = JSON.parse(await fs.readFile(path.join(root, 'config/official-sources.json'), 'utf8'));
const livePath = path.join(root, 'src/data/live-jobs.js');

async function loadExisting() {
  try {
    const mod = await import(`${pathToFileURL(livePath).href}?t=${Date.now()}`);
    return Array.isArray(mod.liveJobs) ? mod.liveJobs : [];
  } catch { return []; }
}

function cleanForStorage(job) {
  const { _searchText, _category, _subject, _sourceJobId, closed, ...clean } = job;
  return clean;
}

function asModule(jobs, meta) {
  return `// AUTO-GENERATED by scripts/refresh-jobs.mjs.\nexport const liveJobs = ${JSON.stringify(jobs, null, 2)};\n\nexport const discoveryMeta = ${JSON.stringify(meta, null, 2)};\n`;
}

function dedupePreferOfficial(jobs = []) {
  const rank = (j) => j?.sourceType === 'official' ? 2 : j?.sourceType === 'secondary' ? 1 : 0;
  const map = new Map();
  for (const job of jobs) {
    if (!job?.id) continue;
    const key = `${String(job.company || '').trim().toLowerCase()}|${String(job.title || '').replace(/[\s【】〖〗()（）\-_]/g,'').toLowerCase()}|${String(job.city || '').trim().toLowerCase()}`;
    const prev = map.get(key);
    if (!prev || rank(job) > rank(prev) || (rank(job) === rank(prev) && String(job.publishedAt || '') > String(prev.publishedAt || ''))) map.set(key, job);
  }
  return [...map.values()];
}

const existing = await loadExisting();
const sourceResults = [];

try {
  const nowcoder = await searchNowcoderJobs(config);
  sourceResults.push({ name: 'nowcoder', ...nowcoder });
  console.log(`[job-refresh:nowcoder] discovered=${nowcoder.stats.discoveredUrls} scanned=${nowcoder.stats.scannedPages} kept=${nowcoder.stats.keptJobs} errors=${nowcoder.stats.errors}`);
} catch (error) {
  console.warn(`[job-refresh:nowcoder] unavailable: ${error.message}`);
}

try {
  const { chromium } = await import('playwright');
  const moka = await searchMokaJobs(config, officialSources.moka || [], { chromium });
  sourceResults.push({ name: 'moka', ...moka });
  console.log(`[job-refresh:moka] portals=${moka.stats.scannedPortals}/${moka.stats.portals} discovered=${moka.stats.discoveredUrls} kept=${moka.stats.keptJobs} errors=${moka.stats.errors}`);
} catch (error) {
  console.warn(`[job-refresh:moka] skipped: ${error.message}`);
}

try {
  const beisen = await searchBeisenJobs(config, officialSources.beisen || []);
  sourceResults.push({ name: 'beisen', ...beisen });
  console.log(`[job-refresh:beisen] portals=${beisen.stats.scannedPortals}/${beisen.stats.portals} rows=${beisen.stats.scannedRows} kept=${beisen.stats.keptJobs} errors=${beisen.stats.errors}`);
} catch (error) {
  console.warn(`[job-refresh:beisen] skipped: ${error.message}`);
}

try {
  const anker = await searchAnkerJobs(config, officialSources.anker, { maxJobs: officialSources.anker?.maxJobs || 10 });
  sourceResults.push({ name: 'anker', ...anker });
  console.log(`[job-refresh:anker] listed=${anker.stats.listed} detailed=${anker.stats.detailed} kept=${anker.stats.keptJobs} errors=${anker.stats.errors}`);
} catch (error) {
  console.warn(`[job-refresh:anker] skipped: ${error.message}`);
}

const freshJobs = sourceResults.flatMap((r) => r.jobs || []).filter((job) => !job.riskTags?.includes('纯销售'));
if (!freshJobs.length) {
  console.warn('[job-refresh] no fresh matching jobs found; keeping existing live job pool unchanged.');
  process.exit(0);
}

// Manually curated seed rows do not have discoveredAt. Auto rows are rebuilt on each successful refresh.
const retainedSeeds = existing.filter((job) => !job.discoveredAt && !job.riskTags?.includes('纯销售'));
const now = new Date();
const merged = dedupePreferOfficial([...freshJobs, ...retainedSeeds])
  .filter((job) => !isClosed('', job.deadline, now) && !job.riskTags?.includes('纯销售'))
  .sort((a,b) => {
    const scoreDiff = relevanceScore(b, config) - relevanceScore(a, config);
    if (scoreDiff) return scoreDiff;
    if (a.sourceType !== b.sourceType) return a.sourceType === 'official' ? -1 : b.sourceType === 'official' ? 1 : 0;
    return String(b.publishedAt || '').localeCompare(String(a.publishedAt || ''));
  })
  .slice(0, Number(config.maxJobs || 300))
  .map(cleanForStorage);

const companies = new Set(merged.map((job) => job.company).filter(Boolean));
const sourceStats = Object.fromEntries(sourceResults.map((r) => [r.name, r.stats]));
const meta = {
  updatedAt: new Date().toISOString(),
  source: '多源：公司官方招聘官网 + 牛客公开职位',
  mode: '官方源优先去重 + 多源扩面 + 前端画像精排',
  stats: { sources: sourceStats, retainedSeeds: retainedSeeds.length, totalJobs: merged.length, companies: companies.size },
  note: '官方招聘官网优先用于去重与核验；二手来源用于扩大岗位发现范围。安克官方源当前为公开 API 首屏有界抓取；纯销售岗位不进入推荐池。投递前仍建议打开原始职位页确认职责和截止日期。'
};

await fs.writeFile(livePath, asModule(merged, meta), 'utf8');
console.log(`[job-refresh] wrote ${merged.length} jobs across ${companies.size} companies; retainedSeeds=${retainedSeeds.length}.`);
