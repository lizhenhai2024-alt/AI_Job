#!/usr/bin/env node
import fs from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const inputPath = path.join(root, 'config/source-discovery.json');
const outputPath = path.join(root, 'src/data/source-discovery.js');
const audit = JSON.parse(await fs.readFile(inputPath, 'utf8'));
const rows = Object.values(audit.companies || {}).map((item) => ({
  name: item.name || '',
  status: item.status || '',
  state: item.state || 'queued',
  provider: item.provider || '',
  officialUrl: item.officialUrl || '',
  reason: item.reason || '',
  attempts: Number(item.attempts || 0),
  lastCheckedAt: item.lastCheckedAt || '',
  nextCheckAfter: item.nextCheckAfter || ''
})).filter((item) => item.name).sort((a, b) => a.name.localeCompare(b.name, 'zh-CN'));
const meta = { updatedAt: audit.updatedAt || '', lastRun: audit.lastRun || { processed: 0, sourcesAdded: 0, errors: 0 } };
const output = `// AUTO-GENERATED by scripts/build-source-discovery.mjs.\nexport const sourceDiscovery = ${JSON.stringify(rows, null, 2)};\n\nexport const sourceDiscoveryMeta = ${JSON.stringify(meta, null, 2)};\n`;
await fs.writeFile(outputPath, output, 'utf8');
console.log(`Built source discovery browser state: ${rows.length} company checks.`);
